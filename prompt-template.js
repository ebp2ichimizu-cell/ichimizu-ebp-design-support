- 施策が実際に実施されたかを確認するために必要か
- 想定メカニズムが機能したかを確認するために必要か
- 最終アウトカムが変化しなかった場合に、どこで因果経路が途切れたかを確認するために必要か
- 現場で現実的に測定可能か
