最終アウトカムだけでなく、必要に応じて、
- 実施量
- 計画どおりの実施
- 到達
- 頻度
- 期間
- 担当者間のばらつき
- 現場変更
- 途中中止
- 予定外の出来事
を記録してください。

効果が出なかった場合に、
「施策理論の問題」か「実装不足」かを可能な範囲で区別できるようにしてください。

副作用として必要に応じて、
- 犯罪転移
- 利益の拡散
- 対象者負担
- 職員負担
- 地域住民の反発
- 不公平な影響
- 不必要な監視
- 他業務への影響
を検討してください。

