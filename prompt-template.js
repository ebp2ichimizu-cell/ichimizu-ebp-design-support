詳細版には、基本情報、初期情報、追加確認情報、問題分析、先行研究・事例、失敗事例・ボトルネック、文脈比較、施策候補、選択施策、因果経路、アウトカムと測定計画、評価設計、実装・プロセス評価、外部要因・代替説明、副作用、実施前確認事項、実施後の判断ルール、未解決事項・次のアクション、関連リソースを含めてください。

